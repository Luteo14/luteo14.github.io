const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const src=fs.readFileSync(path.resolve(__dirname,'../../sport/coach/coach.js'),'utf8');
const first=src.slice(src.indexOf('function unwrap('),src.indexOf('function drawBatteryChart('));
const second=src.slice(src.indexOf('const numeric='),src.indexOf('function dayList('));
const context=vm.createContext({TextDecoder,Uint8Array,Number,Array,Object,Date});
vm.runInContext(first+'\n'+second,context);
const evalFn=(name,...args)=>vm.runInContext(name,context)(...args);
const sleep=[{calendarDate:'2026-10-27',sleepTimeSeconds:28500},{calendarDate:'2026-10-28',sleepTimeSeconds:24840}];
const hrv=[{calendarDate:'2026-10-27',hrvSummary:{lastNightAvg:42,weeklyAvg:42}},{calendarDate:'2026-10-28',hrvSummary:{lastNightAvg:54,weeklyAvg:42}}];
const battery=[{date:'2026-10-27',charged:46,drained:49},{date:'2026-10-28',charged:51,drained:47}];
test('Garmin: sommeil à la racine converti en heures',()=>{const s=evalFn('sleepSeries',sleep);assert.equal(s.length,2);assert.equal(s[0].value,28500/3600);assert.equal(s[1].value,6.9)});
test('Garmin: VFC nocturne prioritaire sur moyenne hebdomadaire',()=>{const rows=evalFn('hrvSeries',hrv);assert.equal(rows[1].value,54)});
test('Garmin: dates Body Battery au champ date',()=>{const rows=evalFn('batterySeries',battery);assert.deepEqual([...rows.map(x=>x.date)],['2026-10-27','2026-10-28']);assert.equal(rows[1].charged,51);assert.equal(rows[1].drained,47)});
test('Garmin: recharge et dépense ne sont pas confondues avec niveau /100',()=>{const rows=evalFn('batterySeries',battery);assert.equal(rows[1].last,null);assert.equal(evalFn('getBodyBattery',battery),null)});
test('Garmin: mesure de niveau explicitement fournie reste utilisable',()=>{const sample=[{date:'2026-10-28',bodyBatteryMostRecentValue:65,charged:51}];assert.equal(evalFn('getBodyBattery',sample).value,65)});
